<?php
$x = 60;
$y = 13;

// Bitwise AND
echo "$x & $y = " . ($x & $y) . "<br>";
// Bitwise OR
echo "$x | $y = " . ($x | $y) . "<br>";
// Bitwise XOR
echo "$x ^ $y = " . ($x ^ $y) . "<br>";
// Shift Left
echo "$x << $y = " . ($x << $y) . "<br>";
// Shift Right
echo "$x >> $y = " . ($x >> $y) . "<br>";
?>